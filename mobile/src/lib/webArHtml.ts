/** WebGL error code → readable name, for diagnostics sent to RN. */
function glErrorName(gl, code) {
  const names = {}
  names[gl.NO_ERROR] = 'NO_ERROR'
  names[gl.INVALID_ENUM] = 'INVALID_ENUM'
  names[gl.INVALID_VALUE] = 'INVALID_VALUE'
  names[gl.INVALID_OPERATION] = 'INVALID_OPERATION'
  names[gl.INVALID_FRAMEBUFFER_OPERATION] = 'INVALID_FRAMEBUFFER_OPERATION'
  names[gl.OUT_OF_MEMORY] = 'OUT_OF_MEMORY'
  if (gl.CONTEXT_LOST_WEBGL !== undefined) names[gl.CONTEXT_LOST_WEBGL] = 'CONTEXT_LOST_WEBGL'
  return names[code] || ('UNKNOWN(' + code + ')')
}

/**
 * Manually compiles+links the exact shader pair as a throwaway raw WebGL
 * program, independent of three.js's own program cache — this is what the
 * requested "shader compile log / shader link log" diagnostics come from.
 * Always runs (not just on failure) so we get real data every time.
 */
function compileDiagnostic(gl, vertSrc, fragSrc) {
  const report = { vertexOk: false, fragmentOk: false, linked: false, vertexLog: '', fragmentLog: '', programLog: '' }
  const vs = gl.createShader(gl.VERTEX_SHADER)
  gl.shaderSource(vs, vertSrc)
  gl.compileShader(vs)
  report.vertexOk = !!gl.getShaderParameter(vs, gl.COMPILE_STATUS)
  report.vertexLog = gl.getShaderInfoLog(vs) || ''

  const fs = gl.createShader(gl.FRAGMENT_SHADER)
  gl.shaderSource(fs, fragSrc)
  gl.compileShader(fs)
  report.fragmentOk = !!gl.getShaderParameter(fs, gl.COMPILE_STATUS)
  report.fragmentLog = gl.getShaderInfoLog(fs) || ''

  const prog = gl.createProgram()
  gl.attachShader(prog, vs)
  gl.attachShader(prog, fs)
  gl.linkProgram(prog)
  report.linked = !!gl.getProgramParameter(prog, gl.LINK_STATUS)
  report.programLog = gl.getProgramInfoLog(prog) || ''

  gl.deleteProgram(prog)
  gl.deleteShader(vs)
  gl.deleteShader(fs)
  return report
}

// ── Generic landmark-driven morph engine ────────────────────────────────────
// Reusable facial deformation: a filter supplies a CONFIG (list of effects,
// each = anchor landmark ids + radius + amplitude + direction), and the
// engine procedurally computes one static per-vertex displacement attribute
// from the canonical mesh — no hand-sculpted per-vertex tables anywhere.
// Directions are expressed in the canonical face basis (x = temple→temple,
// y = chin→forehead, z = out of the face — verified identical to the live
// rig's basis construction), so the vertex shader rotates them with the
// tracked head every frame. Displacement rides ON TOP of the live landmark
// positions, so expressions (smiles etc.) keep working — the morph is a
// constant anatomical offset in face-local space, not a replacement pose.
// Future filters (baby, monster, zombie, fat/thin, beauty) = new configs.
const CANONICAL_POSITIONS = CANONICAL.positions   // 468×3, canonical cm
const SLOT_OF_LANDMARK = (() => {
  const map = {}
  for (let s = 0; s < CANONICAL.landmarkIndex.length; s++) map[CANONICAL.landmarkIndex[s]] = s
  return map
})()
function canonPos(slot, out) {
  out.set(CANONICAL_POSITIONS[slot * 3], CANONICAL_POSITIONS[slot * 3 + 1], CANONICAL_POSITIONS[slot * 3 + 2])
  return out
}
const CANON_TEMPLE_CM = (() => {
  const a = canonPos(SLOT_OF_LANDMARK[234], new THREE.Vector3())
  const b = canonPos(SLOT_OF_LANDMARK[454], new THREE.Vector3())
  return a.distanceTo(b)   // ≈15.33 — the px-per-cm anchor for mm-accurate amplitudes
})()

/** Per-vertex smooth normals of the canonical mesh (procedural, from topology). */
function canonicalNormals(indexTriangles) {
  const n = new Float32Array(468 * 3)
  const pa = new THREE.Vector3(), pb = new THREE.Vector3(), pc = new THREE.Vector3()
  const ab = new THREE.Vector3(), ac = new THREE.Vector3(), fn = new THREE.Vector3()
  for (let i = 0; i < indexTriangles.length; i += 3) {
    const s0 = indexTriangles[i], s1 = indexTriangles[i + 1], s2 = indexTriangles[i + 2]
    canonPos(s0, pa); canonPos(s1, pb); canonPos(s2, pc)
    ab.subVectors(pb, pa); ac.subVectors(pc, pa); fn.crossVectors(ab, ac)
    for (const s of [s0, s1, s2]) {
      n[s * 3] += fn.x; n[s * 3 + 1] += fn.y; n[s * 3 + 2] += fn.z
    }
  }
  const v = new THREE.Vector3()
  for (let s = 0; s < 468; s++) {
    v.set(n[s * 3], n[s * 3 + 1], n[s * 3 + 2])
    // canonical z faces the viewer; normals must point OUT of the face
    if (v.z < 0) v.negate()
    v.normalize()
    n[s * 3] = v.x; n[s * 3 + 1] = v.y; n[s * 3 + 2] = v.z
  }
  return n
}

function smoothFalloff(d, radius) {
  const t = Math.min(1, Math.max(0, d / radius))
  return 1 - t * t * (3 - 2 * t)
}

/**
 * effects: [{ centers: [landmark ids], radiusCm, ampMm, dir: 'in'|'out'|'down' }]
 * 'in'/'out' = along the vertex's own canonical normal (in = volume loss,
 * out = volume gain); 'down' = -y in face space (gravity sag).
 * Protection is fully procedural: every vertex on a topology BOUNDARY edge
 * (face oval + both eye holes + the inner-mouth hole — computed from the
 * index buffer, not listed by hand) plus small zones around the nostrils
 * and eye centers suppress deformation with a soft radial falloff, which
 * covers every "do not deform" region (eyes, eyelids, lips, nostrils,
 * face/forehead outline) without hard transitions.
 */
function buildMorphOffsets(effects, indexTriangles) {
  const edgeCount = {}
  for (let i = 0; i < indexTriangles.length; i += 3) {
    const t0 = indexTriangles[i], t1 = indexTriangles[i + 1], t2 = indexTriangles[i + 2]
    for (const [a, b] of [[t0, t1], [t1, t2], [t2, t0]]) {
      const key = a < b ? a + '_' + b : b + '_' + a
      edgeCount[key] = (edgeCount[key] || 0) + 1
    }
  }
  const boundarySlots = new Set()
  for (const key of Object.keys(edgeCount)) {
    if (edgeCount[key] === 1) {
      const parts = key.split('_')
      boundarySlots.add(parseInt(parts[0], 10))
      boundarySlots.add(parseInt(parts[1], 10))
    }
  }
  const normals = canonicalNormals(indexTriangles)
  const vp = new THREE.Vector3(), cp = new THREE.Vector3(), acc = new THREE.Vector3(), dir = new THREE.Vector3()

  // soft protection field per vertex (1 = fully deformable, 0 = frozen)
  const eyeCenters = []
  for (const ring of [CAP_RING_LEFT_EYE, CAP_RING_RIGHT_EYE]) {
    const c = new THREE.Vector3()
    let count = 0
    ring.forEach((lm) => {
      if (SLOT_OF_LANDMARK[lm] !== undefined) { c.add(canonPos(SLOT_OF_LANDMARK[lm], cp)); count++ }
    })
    if (count) eyeCenters.push(c.multiplyScalar(1 / count))
  }
  const nostrilSlots = [SLOT_OF_LANDMARK[129], SLOT_OF_LANDMARK[358]]
  const protection = new Float32Array(468)
  for (let s = 0; s < 468; s++) {
    canonPos(s, vp)
    let minBoundary = Infinity
    boundarySlots.forEach((bs) => {
      const d = vp.distanceTo(canonPos(bs, cp))
      if (d < minBoundary) minBoundary = d
    })
    let prot = 1 - smoothFalloff(minBoundary, 0.9)      // 0 at boundary → 1 at 0.9cm inside
    for (const ec of eyeCenters) prot *= 1 - smoothFalloff(vp.distanceTo(ec), 1.7)
    for (const ns of nostrilSlots) prot *= 1 - smoothFalloff(vp.distanceTo(canonPos(ns, cp)), 0.7)
    protection[s] = prot
  }

  const out = new Float32Array(468 * 3)
  for (const effect of effects) {
    const ampCm = effect.ampMm / 10
    const centerSlots = effect.centers.map((lm) => SLOT_OF_LANDMARK[lm]).filter((s) => s !== undefined)
    for (let s = 0; s < 468; s++) {
      if (protection[s] <= 0.001) continue
      canonPos(s, vp)
      let minD = Infinity
      for (const cs of centerSlots) {
        const d = vp.distanceTo(canonPos(cs, cp))
        if (d < minD) minD = d
      }
      const w = smoothFalloff(minD, effect.radiusCm) * protection[s]
      if (w <= 0.001) continue
      if (effect.dir === 'down') dir.set(0, -1, 0)
      else {
        dir.set(normals[s * 3], normals[s * 3 + 1], normals[s * 3 + 2])
        if (effect.dir === 'in') dir.negate()
      }
      out[s * 3] += dir.x * ampCm * w
      out[s * 3 + 1] += dir.y * ampCm * w
      out[s * 3 + 2] += dir.z * ampCm * w
    }
  }
  // safety clamp: overlapping zones may sum past the spec — cap at 4mm
  let maxDisp = 0, affected = 0
  for (let s = 0; s < 468; s++) {
    acc.set(out[s * 3], out[s * 3 + 1], out[s * 3 + 2])
    const len = acc.length()
    if (len > 0.4) {
      acc.multiplyScalar(0.4 / len)
      out[s * 3] = acc.x; out[s * 3 + 1] = acc.y; out[s * 3 + 2] = acc.z
    }
    if (len > 0.005) affected++
    if (len > maxDisp) maxDisp = Math.min(len, 0.4)
  }
  return { offsets: out, maxDispMm: maxDisp * 10, affectedVerts: affected, boundaryVerts: boundarySlots.size }
}

