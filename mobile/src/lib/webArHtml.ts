/**
 * Reads a same-origin file:// URL as an ArrayBuffer via XMLHttpRequest.
 * Chromium's fetch() (which THREE.FileLoader/GLTFLoader.loadAsync use
 * internally) rejects the file: scheme outright in Android's WebView —
 * that is the real cause of "TypeError: Failed to fetch" for local .glb
 * loads, NOT a permissions or CORS problem. XHR has always supported
 * file:// reads from a file:// page, so we use it directly and feed the
 * bytes to GLTFLoader.parse() ourselves.
 */
function loadArrayBuffer(url) {
  return new Promise((resolve, reject) => {
    const xhr = new XMLHttpRequest()
    xhr.open('GET', url, true)
    xhr.responseType = 'arraybuffer'
    xhr.onload = () => {
      if (xhr.status === 0 || xhr.status === 200) resolve(xhr.response)
      else reject(new Error('xhr status ' + xhr.status + ' for ' + url))
    }
    xhr.onerror = () => reject(new Error('xhr network error for ' + url))
    xhr.ontimeout = () => reject(new Error('xhr timeout for ' + url))
    xhr.send()
  })
}

async function buildTemplate(id) {
  const def = FILTERS[id]
  if (!def) throw new Error('unknown filter ' + id)
  let object
  if (def.url) {
    const resolvedUrl = new URL(def.url, location.href).href
    rnPost({ type: 'debug', message: 'loading filter ' + id + ' from ' + resolvedUrl })
    let buffer
    try {
      buffer = await loadArrayBuffer(resolvedUrl)
    } catch (e) {
      throw new Error('fetch ' + resolvedUrl + ' failed: ' + (e && e.message || e))
    }
    const gltf = await new Promise((resolve, reject) => {
      gltfLoader.parse(buffer, resolvedUrl, resolve, reject)
    })
    object = gltf.scene || gltf.scenes[0]
  } else if (def.build) {
    object = def.build()
  } else {
    throw new Error('filter ' + id + ' has neither url nor build')
  }
  if (def.rotate) {
    object.rotation.set(def.rotate[0], def.rotate[1], def.rotate[2])
    object.updateMatrixWorld(true)
  }
  return normalizeModel(object, def.width)
}

/** Cached, de-duplicated model load. Never adds anything to the live scene. */
function loadTemplate(id) {
  if (modelTemplates[id]) return Promise.resolve(modelTemplates[id])
  if (modelLoadPromises[id]) return modelLoadPromises[id]
  const promise = buildTemplate(id)
    .then((template) => {
      delete modelLoadPromises[id]
      if (isDestroyed()) return null
      modelTemplates[id] = template
      rnPost({ type: 'filterReady', id })
      return template
    })
    .catch((e) => {
      delete modelLoadPromises[id]
      if (!isDestroyed()) rnPost({ type: 'filterError', id, message: String(e && e.message || e) })
      throw e
    })
  modelLoadPromises[id] = promise
  return promise
}

/**
 * Recursively disposes geometries/materials/textures on an Object3D subtree.
 * Only ever called on objects that are NOT shared with the template cache
 * (see the warning in clearActiveFilter() below) — currently that means:
 * cached accessory templates themselves (at full page teardown) and the
 * aging mesh / occluder (also at teardown). Safe to call on null/undefined.
 */
function disposeObject3D(root) {
  if (!root) return
  root.traverse((obj) => {
    if (obj.geometry) obj.geometry.dispose()
    const mats = Array.isArray(obj.material) ? obj.material : (obj.material ? [obj.material] : [])
    for (const mat of mats) {
      for (const key of Object.keys(mat)) {
        const value = mat[key]
        if (value && value.isTexture) value.dispose()
      }
      mat.dispose()
    }
  })
}

/**
 * Stamps every node of an accessory instance (the clone's own root AND all
 * its descendants — GLB scene nodes, meshes, bones) as belonging to this
 * filter. clearActiveFilter() below trusts this marker, not scene position,
 * to decide what to remove — so an accessory can never survive a switch even
 * if something ends up parented outside filterRoot.
 */
function markFilterOwned(root, id) {
  root.traverse((obj) => {
    obj.userData.filterOwned = true
    obj.userData.filterId = id
  })
}

/**
 * Single point of truth for "nothing from the previous filter may remain."
 * Called at the START of every showFilter(), before anything about the new
 * filter is decided — so no code path can show a new filter without first
 * clearing the old one, whichever kind it was (accessory or aging).
 *
 * Walks the WHOLE scene graph (not just filterRoot) and removes every object
 * carrying userData.filterOwned === true. Camera, lights, agingMesh,
 * occluderMesh and renderer internals are never marked by any code path, so
 * this sweep structurally cannot touch them.
 *
 * IMPORTANT: this does NOT dispose the accessory clones' geometry/material.
 * filterRoot holds a template.clone(true) — Object3D.clone() deep-clones
 * the scene-graph nodes, but each Mesh's geometry/material stay SHARED
 * BY REFERENCE with the cached template in modelTemplates[id] (three.js
 * does this deliberately, precisely so clones are cheap). Disposing a
 * clone's geometry/material would dispose the CACHED template's GPU
 * resources too, permanently breaking that filter the next time it's
 * selected. Real disposal of cached resources only happens once, at full
 * page teardown, in destroyAll() below — that is the technically correct
 * "where appropriate" per the cleanup requirements.
 */
function clearActiveFilter() {
  const found = []
  scene.traverse((obj) => {
    if (obj.userData && obj.userData.filterOwned === true) found.push(obj)
  })
  const markedSet = new Set(found)
  // Only the root of each marked subtree needs an explicit remove() call —
  // removing a node takes its (also-marked) descendants with it for free.
  const roots = found.filter((obj) => !obj.parent || !markedSet.has(obj.parent))

  rnPost({
    type: 'diag',
    stage: 'clearActiveFilter-before',
    activeFilterId: currentFilter,
    filterOwnedObjectsFound: found.length,
    filterOwnedRootsFound: roots.length,
  })

  const removedLog = roots.map((obj) => ({
    name: obj.name || obj.type || '(unnamed)',
    parentName: obj.parent ? (obj.parent.name || obj.parent.type || '(unnamed)') : '(none)',
    filterId: obj.userData.filterId,
  }))
  for (const obj of roots) {
    if (obj.parent) obj.parent.remove(obj)
  }

  filterRoot.visible = false
  if (occluderMesh) occluderMesh.visible = false
  if (agingMesh) agingMesh.visible = false

  let remaining = 0
  scene.traverse((obj) => {
    if (obj.userData && obj.userData.filterOwned === true) remaining++
  })

  rnPost({
    type: 'diag',
    stage: 'clearActiveFilter-after',
    activeFilterId: currentFilter,
    removed: removedLog,
    filterOwnedRemaining: remaining,
  })

  // Framebuffer-clear investigation: force one immediate clean frame right
  // here, synchronously, instead of waiting for the next scheduled
  // requestAnimationFrame. renderer.autoClear is true (three.js default,
  // never overridden anywhere in this file — verified against the r160
  // source), so renderer.render() already clears color/depth/stencil before
  // drawing every frame; this call does not depend on that default staying
  // true, and it means the removed GLB's pixels are gone from the canvas the
  // instant clearActiveFilter() runs, not up to one frame later.
  renderer.clear(true, true, true)
  renderer.render(scene, camera3)
  // Also watch the next few loop() frames' pre/post-render state — see
  // renderDiagFramesRemaining's declaration for why this is capped rather
  // than logged every frame.
  renderDiagFramesRemaining = 3
}

// Monotonic token: a showFilter() call only applies its result if it is still
// the most recent request by the time its (async) load resolves — this is
// what cancels a stale filter switch (e.g. Cat tapped, then King tapped
// before Cat's GLB finishes loading) instead of racing the UI.
let filterRequestVersion = 0

async function showFilter(id) {
  currentFilter = id
  const myVersion = ++filterRequestVersion
  clearActiveFilter()
  const def = FILTERS[id]
  if (def && def.kind === 'aging') {
    // No accessory template at all for the aging effect right now — the
    // render loop drives agingMesh directly every frame (updateAgingMesh),
    // re-showing it since clearActiveFilter() just hid it above.
    rnPost({ type: 'filterReady', id })
    return
  }
  let template
  try {
    template = await loadTemplate(id)
  } catch (e) {
    return // already reported via filterError
  }
  // Superseded by a newer showFilter() while this GLB load/build was in
  // flight, or the page was torn down meanwhile — abort placement, do not
  // add a now-stale accessory on top of whatever the newer call already set.
  if (isDestroyed() || myVersion !== filterRequestVersion) return
  // A newer showFilter() may have run (and cleared) while we were awaiting
  // the load above — clear once more so we never add on top of anything,
  // guaranteeing only one accessory instance is ever live at a time.
  clearActiveFilter()
  if (template) {
    const instance = template.clone(true)
    markFilterOwned(instance, id)
    filterRoot.add(instance)
  }
}

