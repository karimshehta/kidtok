/**
 * Drops any triangle from fullSlotTriangles whose three vertices (mapped
 * through landmarkIndex from internal mesh "slot" to real MediaPipe landmark
 * id) all fall inside one of the eye/mouth contour rings above. Returns the
 * reduced index list plus a per-ring removal count for verification.
 */
function computeOpenTriangles(fullSlotTriangles, landmarkIndex) {
  const kept = []
  let mouthRemoved = 0
  let leftEyeRemoved = 0
  let rightEyeRemoved = 0
  for (let i = 0; i < fullSlotTriangles.length; i += 3) {
    const s0 = fullSlotTriangles[i]
    const s1 = fullSlotTriangles[i + 1]
    const s2 = fullSlotTriangles[i + 2]
    const l0 = landmarkIndex[s0]
    const l1 = landmarkIndex[s1]
    const l2 = landmarkIndex[s2]
    if (CAP_RING_MOUTH.has(l0) && CAP_RING_MOUTH.has(l1) && CAP_RING_MOUTH.has(l2)) { mouthRemoved++; continue }
    if (CAP_RING_LEFT_EYE.has(l0) && CAP_RING_LEFT_EYE.has(l1) && CAP_RING_LEFT_EYE.has(l2)) { leftEyeRemoved++; continue }
    if (CAP_RING_RIGHT_EYE.has(l0) && CAP_RING_RIGHT_EYE.has(l1) && CAP_RING_RIGHT_EYE.has(l2)) { rightEyeRemoved++; continue }
    kept.push(s0, s1, s2)
  }
  return {
    triangles: kept,
    fullCount: fullSlotTriangles.length / 3,
    keptCount: kept.length / 3,
    mouthRemoved,
    leftEyeRemoved,
    rightEyeRemoved,
    totalRemoved: mouthRemoved + leftEyeRemoved + rightEyeRemoved,
  }
}

