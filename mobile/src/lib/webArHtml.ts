function updateRig(landmarks) {
  lmToScreen(landmarks[LM.templeL], _a)
  lmToScreen(landmarks[LM.templeR], _b)
  const rawWidth = Math.max(1, _a.distanceTo(_b))
  _right.subVectors(_b, _a).normalize()
  lmToScreen(landmarks[LM.forehead], _a)
  lmToScreen(landmarks[LM.chin], _c)
  _up.subVectors(_a, _c).normalize()
  _fwd.crossVectors(_right, _up).normalize()
  _up.crossVectors(_fwd, _right).normalize()
  _basis.makeBasis(_right, _up, _fwd)
  _rawQuat.setFromRotationMatrix(_basis)
  lmToScreen(landmarks[LM.between], _a)

  if (rig.fresh) {
    rig.position.copy(_a)
    rig.quaternion.copy(_rawQuat)
    rig.faceWidth = rawWidth
    rig.fresh = false
  } else {
    rig.position.lerp(_a, POS_ALPHA)
    rig.quaternion.slerp(_rawQuat, ROT_ALPHA)
    rig.faceWidth += (rawWidth - rig.faceWidth) * SCALE_ALPHA
  }
}

